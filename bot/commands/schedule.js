// commands/schedule.js
module.exports = function showSchedule(bot, chatId, mode = "class") {
  const m = String(mode).toLowerCase();

  //
  // ✅ HIP-HOP CLASS — мастер-класс (45 BYN)
  //
  if (m === "class") {
    return bot.sendMessage(
      chatId,
      [
        '*HIP-HOP CLASS — мастер-класс*',
        'Дата: 15 ноября',
        'Время: 18:00–20:00',
        'Место: TORITEAM STUDIO (Дзержинского 17/2, вход со двора)',
        '',
        'Стоимость участия: *45 BYN*',
      ].join('\n'),
      { parse_mode: "Markdown" }
    );
  }

  //
  // ✅ Команда YNK — обновлённый текст
  //
  return bot.sendMessage(
    chatId,
    [
      '*Прежде чем попасть в команду, необходимо пройти отбор!*',
      'Отбор проходит в формате мастер-класса:',
      '',
      '🗓 *Дата:* 15.11',
      '⏰ *Время:* 18:00–20:00',
      '📍 *Место:* TORITEAM STUDIO',
      '    г. Новополоцк, ул. Дзержинского 17/2 (вход со двора)',
      '',
      '━━━━━━━━━━━━━━',
      '*Информация о команде YNK*',
      '━━━━━━━━━━━━━━',
      '',
      'Регулярные тренировки:',
      'Вт / Чт — 21:00–23:00',
      'Место: TORITEAM STUDIO (Дзержинского 17к2)',
      '',
      'Стоимость абонемента: *90 BYN*',
      '',
      'Формат команды:',
      '• регулярные тренировки',
      '• участие в чемпионатах',
      '• классы приглашённых хореографов',
      '• съёмки и контент-проекты',
    ].join('\n'),
    { parse_mode: "Markdown" }
  );
};
